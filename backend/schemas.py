"""
Pydantic v2 schemas for request validation and response serialization.
Uses strict typing, Field constraints, and ConfigDict(from_attributes=True).
"""

from datetime import datetime
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field, ConfigDict


# ============================================================================
# Driver Schemas
# ============================================================================

class DriverBase(BaseModel):
    name: str = Field(..., min_length=2, max_length=100)
    license_number: str = Field(..., min_length=4, max_length=50)


class DriverCreate(DriverBase):
    rolling_safety_score: float = Field(default=100.0, ge=0.0, le=100.0)


class DriverResponse(DriverBase):
    id: int
    rolling_safety_score: float
    model_config = ConfigDict(from_attributes=True)


# ============================================================================
# Vehicle Schemas
# ============================================================================

class VehicleBase(BaseModel):
    registration: str = Field(..., min_length=3, max_length=50)
    permitted_capacity: int = Field(default=32, ge=1, le=150)


class VehicleCreate(VehicleBase):
    assigned_driver_id: Optional[int] = None
    sensor_mode: str = Field(default="GPS_LOCKED")


class VehicleResponse(VehicleBase):
    id: int
    assigned_driver_id: Optional[int] = None
    current_lat: Optional[float] = None
    current_lon: Optional[float] = None
    current_speed: float = 0.0
    sensor_mode: str
    last_seen: datetime
    driver: Optional[DriverResponse] = None
    model_config = ConfigDict(from_attributes=True)


# ============================================================================
# Violation Event & Outbox Ingestion Schemas
# ============================================================================

class ViolationEventCreate(BaseModel):
    id: str = Field(..., description="UUID generated by mobile edge Blackbox")
    vehicle_registration: Optional[str] = Field(None, description="Registration e.g. JK02-1234")
    vehicle_id: Optional[int] = None
    driver_id: Optional[int] = None
    violation_type: str = Field(
        ...,
        description="OVERSPEED_CURVE | DROWSINESS | DISTRACTION | PHONE_USE | OVERCROWDING | SOS_ALERT",
    )
    severity: str = Field(..., description="ADVISORY | CRITICAL")
    timestamp_device: datetime
    lat: float = Field(..., ge=-90.0, le=90.0)
    lon: float = Field(..., ge=-180.0, le=180.0)
    speed_actual: float = Field(..., ge=0.0)
    speed_safe: Optional[float] = None
    curve_radius: Optional[float] = None
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)
    sensor_mode: str = Field(default="GPS_LOCKED")
    evidence_clip_ref: Optional[str] = None
    prev_hash: str = Field(..., min_length=16, max_length=64)
    record_hash: str = Field(..., min_length=16, max_length=64)
    seq_no: int = Field(..., ge=1)


class ViolationEventResponse(BaseModel):
    id: str
    vehicle_id: Optional[int] = None
    driver_id: Optional[int] = None
    violation_type: str
    severity: str
    timestamp_device: datetime
    timestamp_server: datetime
    arrived_late: bool
    lat: float
    lon: float
    speed_actual: float
    speed_safe: Optional[float] = None
    curve_radius: Optional[float] = None
    confidence: float
    sensor_mode: str
    evidence_clip_ref: Optional[str] = None
    prev_hash: str
    record_hash: str
    seq_no: int
    model_config = ConfigDict(from_attributes=True)


class OutboxSyncRequest(BaseModel):
    events: List[ViolationEventCreate] = Field(
        ..., description="Batch array of unsynced violation records from mobile IndexedDB Blackbox"
    )


class OutboxSyncResponse(BaseModel):
    status: str = "synced"
    received: int
    new_records: int
    duplicates: int
    updated_driver_scores: Dict[int, float] = Field(default_factory=dict)


# ============================================================================
# Telemetry Heartbeat Schemas
# ============================================================================

class TelemetryHeartbeatRequest(BaseModel):
    vehicle_registration: str = Field(..., min_length=2)
    lat: float = Field(..., ge=-90.0, le=90.0)
    lon: float = Field(..., ge=-180.0, le=180.0)
    speed: float = Field(..., ge=0.0)
    heading: Optional[float] = Field(None, ge=0.0, le=360.0)
    sensor_mode: str = Field(default="GPS_LOCKED")
    driver_id: Optional[int] = None
    cabin_occupancy: Optional[int] = None
    active_advisory: Optional[str] = None


class TelemetryHeartbeatResponse(BaseModel):
    status: str = "ok"
    vehicle_registration: str
    sensor_mode: str
    server_timestamp: datetime
    active_curve_advisory: Optional[Dict[str, Any]] = None


# ============================================================================
# Cryptographic Chain Verification Schemas
# ============================================================================

class ChainVerifyDetail(BaseModel):
    seq_no: int
    event_id: str
    violation_type: str
    timestamp_device: str
    speed_actual: float
    stored_hash: str
    recomputed_hash: str
    prev_hash: str
    valid: bool
    reason: Optional[str] = None


class ChainVerifyResponse(BaseModel):
    vehicle: str
    chain_intact: bool
    total_records: int
    tampered_seq_no: Optional[int] = None
    details: List[ChainVerifyDetail] = Field(default_factory=list)


# ============================================================================
# Evidence Access & DPDP Act 2023 Schemas
# ============================================================================

class EvidenceResponse(BaseModel):
    event_id: str
    vehicle_registration: Optional[str] = None
    violation_type: str
    severity: str
    timestamp_device: datetime
    evidence_payload: str
    is_encrypted: bool
    watermark: Dict[str, Any]


class AuditLogResponse(BaseModel):
    id: int
    actor_role: str
    actor_id: str
    violation_id: Optional[str] = None
    accessed_at: datetime
    purpose: str
    model_config = ConfigDict(from_attributes=True)


# ============================================================================
# Passenger Feedback & Crowdsourced Safety Schemas
# ============================================================================

class PassengerFeedbackCreate(BaseModel):
    vehicle_registration: Optional[str] = None
    vehicle_id: Optional[int] = None
    trip_id: Optional[str] = None
    rating: int = Field(..., ge=1, le=5)
    comment: Optional[str] = None
    is_sos: bool = False


class PassengerFeedbackResponse(BaseModel):
    id: int
    vehicle_id: int
    trip_id: Optional[str] = None
    rating: int
    comment: Optional[str] = None
    is_sos: bool
    created_at: datetime
    model_config = ConfigDict(from_attributes=True)
